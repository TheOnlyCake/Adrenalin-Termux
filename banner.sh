gradient() {
    local r1=$1 g1=$2 b1=$3
    local r2=$4 g2=$5 b2=$6
    local text="$7"

    local total=$(printf '%s\n' "$text" | wc -l)
    local i=0

    while IFS= read -r line; do
        if [ "$total" -le 1 ]; then
            t=0
        else
            t=$(awk "BEGIN {print $i/($total-1)}")
        fi

        r=$(awk "BEGIN {printf \"%.0f\", $r1 + ($r2-$r1)*$t}")
        g=$(awk "BEGIN {printf \"%.0f\", $g1 + ($g2-$g1)*$t}")
        b=$(awk "BEGIN {printf \"%.0f\", $b1 + ($b2-$b1)*$t}")

        printf "\033[38;2;%s;%s;%sm%s\033[0m\n" "$r" "$g" "$b" "$line"

        i=$((i+1))
    done <<< "$text"
}

