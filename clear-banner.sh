'

TOTAL=$(printf '%s\n' "$TEXT" | wc -l)
LINE=0

while IFS= read -r text; do

    if [ "$TOTAL" -gt 1 ]; then
        T=$(awk "BEGIN {print $LINE/($TOTAL-1)}")
    else
        T=0
    fi

    # Azul profundo -> azul claro
    R=$(awk "BEGIN {printf \"%.0f\", 20 + (80-20)*$T}")
    G=$(awk "BEGIN {printf \"%.0f\", 80 + (200-80)*$T}")
    B=$(awk "BEGIN {printf \"%.0f\", 180 + (255-180)*$T}")

    printf "\033[38;2;%s;%s;%sm%s\033[0m\n" "$R" "$G" "$B" "$text"

    LINE=$((LINE + 1))

done <<< "$TEXT"

